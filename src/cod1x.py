"""
cod1x.py: Call of Duty multiplayer through CoD1x (github.com/xtnded/codextended-client)

CoD1x needs CoD1 1.1. Steam sells 1.5, and Steam puts UO in the same folder,
so DeckOps leaves the game folder alone and builds a second copy beside it:

  <CoD1>/deckops_cod1x/
    CoDMP.exe, cod1x.dll   from the CoD1x release, checked against its sha256 digest
    Main/*_mp_x86.dll      the 1.1 MP DLLs, from the game's own pak6.pk3
    Main/pak0-6, localized_*_pak0-1, root DLLs, miles/
                           hard links to the game's files (same drive, no extra space)
    pb/                    a real copy, PunkBuster writes into it
    Main/codkey            the owner's CD key (own_codkey / steam_codkey)
    deckops_cod1x.json     tag + digest of the installed release

The 1.5 patch paks (pak7 and up, localized_*_pak2 and up) and mods such as
IW-Pad's SP menu stay out. Nothing the game writes is ever a link, so it can
never write into the Steam folder. Only CoD1's own files are used, UO is not needed.

A disc copy still on 1.1 needs no copy: CoD1x goes into the game folder the
way its own zip does it (stock exe kept as CoDMP_old.exe). A disc copy patched
to 1.5 gets the copy, like Steam.
"""

import json
import os
import re
import shutil
import zipfile

from log import get_logger
from net import download, github_asset

_log = get_logger(__name__)

REPO = "xtnded/codextended-client"
ASSET = "CoD1x_Archive.zip"
COPY = "deckops_cod1x"
META = "deckops_cod1x.json"
_STOCK = re.compile(r"(pak[0-6]|localized_[a-z]+_pak[01])\.pk3$", re.I)
_PATCH15 = re.compile(r"(pak[7-9a-z]|localized_[a-z]+_pak[2-9])\.pk3$", re.I)
_MP_DLLS = ("cgame_mp_x86.dll", "game_mp_x86.dll", "ui_mp_x86.dll")
_CODKEY_TAIL = ("// generated by CoD, do not modify\r\n// Do not give this file to ANYONE.\r\n"
                "// Infinity Ward and Activision will NOT ask you to send this file to them.\r\n")


def _child(d, name):
    """The entry of d that matches name in any case, else d/name."""
    return next((os.path.join(d, e) for e in os.listdir(d) if e.lower() == name), os.path.join(d, name))


def _link(src, dst):
    if not os.path.exists(dst):
        os.link(src, dst)


def in_place(game_dir):
    """True for a disc copy still on 1.1 (no 1.5 paks), which takes CoD1x in its own folder."""
    if "/steamapps/common/" in game_dir.replace("\\", "/"):
        return False
    # UO's CoDUOx uses a cod1x.dll in the same root, so CoD1x takes the copy there
    if os.path.isfile(_child(game_dir, "coduomp.exe")):
        return False
    try:
        return not any(_PATCH15.fullmatch(f) for f in os.listdir(_child(game_dir, "main")))
    except OSError:
        return False


def client_dir(game_dir):
    """Folder CoD1x runs from: the game folder (1.1 disc copy) or the copy."""
    return game_dir if in_place(game_dir) else os.path.join(game_dir, COPY)


def build_copy(game_dir):
    """Build or refresh <game_dir>/deckops_cod1x from the game's own files. Returns its path."""
    c = os.path.join(game_dir, COPY)
    os.makedirs(c, exist_ok=True)
    for e in os.listdir(game_dir):
        p, low = os.path.join(game_dir, e), e.lower()
        # cod1x.dll in a UO folder is CoDUOx's. A link would let _fetch_client write CoD1x over it
        if os.path.isfile(p) and (low == "localization.txt" or
                                  low.endswith(".dll") and low != "cod1x.dll" and not low.startswith(("iw-pad", "uo_"))):
            _link(p, os.path.join(c, e))
    miles = _child(game_dir, "miles")
    if os.path.isdir(miles):
        os.makedirs(os.path.join(c, "miles"), exist_ok=True)
        for f in os.listdir(miles):
            _link(os.path.join(miles, f), os.path.join(c, "miles", f))
    pb = _child(game_dir, "pb")
    if os.path.isdir(pb) and not os.path.exists(os.path.join(c, "pb")):
        shutil.copytree(pb, os.path.join(c, "pb"))

    main, cm = _child(game_dir, "main"), os.path.join(c, "Main")
    os.makedirs(cm, exist_ok=True)
    for f in os.listdir(main):
        if _STOCK.fullmatch(f):
            _link(os.path.join(main, f), os.path.join(cm, f))
    # The 1.1 MP DLLs: pak6 of a 1.5 copy holds them, a 1.1 copy has them loose in Main
    p6 = _child(main, "pak6.pk3")
    if os.path.isfile(p6):
        with zipfile.ZipFile(p6) as z:
            for n in _MP_DLLS:
                with open(os.path.join(cm, n), "wb") as out:
                    out.write(z.read(n))
    else:
        for n in _MP_DLLS:
            shutil.copy2(_child(main, n), os.path.join(cm, n))
    return c


def own_codkey(copy_dir, game_dir):
    """Disc copy: its Main/codkey into the copy, where CoD1x reads it.

    A codkey already in the copy (typed in game) is kept. Without one the game
    asks for the key once. Returns True when the file is there afterwards."""
    dest = os.path.join(copy_dir, "Main", "codkey")
    if os.path.isfile(dest):
        return True
    own = _child(_child(game_dir, "main"), "codkey")
    if not os.path.isfile(own):
        _log.info("CoD1x: no codkey in the game folder, the game asks for it")
        return False
    shutil.copy2(own, dest)
    _log.info("CoD1x: CD key copied from the game folder")
    return True


def steam_codkey(copy_dir, steam_root, appid="2620"):
    """Steam copy: the owner's key into the copy's Main/codkey.

    Steam keeps it in legacycompat/evaluatorscript_<appid>.vdf and normally
    puts it in the game prefix's registry, which CoD1x does not read. A codkey
    already in the copy (typed in game) is kept. The key is never logged.
    Returns True when the file is there afterwards."""
    dest = os.path.join(copy_dir, "Main", "codkey")
    if os.path.isfile(dest):
        return True
    try:
        with open(os.path.join(steam_root, "legacycompat", f"evaluatorscript_{appid}.vdf"),
                  errors="replace") as f:
            m = re.search(r'"legacycdkey"\s+"([A-Z0-9]{20})"', f.read())
    except OSError:
        m = None
    if not m:
        _log.info("CoD1x: no Steam CD key yet (CoD1 not started from Steam), the game asks for it")
        return False
    with open(dest, "w", newline="") as f:
        f.write(m.group(1) + "\r\n" + _CODKEY_TAIL)
    _log.info("CoD1x: CD key written from Steam")
    return True


def _fetch_client(copy_dir, prog, release=None):
    """CoDMP.exe + cod1x.dll from the release, skipped when tag and digest match the saved ones."""
    url, dg = release or github_asset(REPO, ASSET)
    tag = url.split("/")[-2]
    from cod3recomp import _saved
    have = all(os.path.isfile(os.path.join(copy_dir, n)) for n in ("CoDMP.exe", "cod1x.dll"))
    if dg and have and _saved(copy_dir, META) == {"tag": tag, "digest": dg}:
        return
    z = os.path.join(copy_dir, ASSET)
    download(url, z, prog, "CoD1x", digest=dg)
    with zipfile.ZipFile(z) as zf:
        for n in ("cod1x.dll", "CoDMP.exe"):
            with open(os.path.join(copy_dir, n), "wb") as out:
                out.write(zf.read(n))
    os.remove(z)
    # An unverified download saves no version, so the next launch fetches a verified copy
    with open(os.path.join(copy_dir, META), "w") as f:
        json.dump({"tag": tag, "digest": dg} if dg else {}, f)


def install_cod1x(game: dict, steam_root: str, on_progress=None, source="steam"):
    """Build the 1.1 copy, fetch CoD1x into it and set up the CD key. Raises on failure.

    Steam (1.5): the 1.1 MP DLLs come from pak6, the key from Steam's files.
    Own (disc, 1.1 or 1.5): the key comes from the disc copy's Main/codkey."""
    def prog(pct, msg):
        _log.info(msg)
        if on_progress:
            on_progress(pct, msg)

    d = game["install_dir"]
    if source == "own" and in_place(d):
        prog(0, "Installing CoD1x into the game folder...")
        # Stock exe kept under the name CoD1x's own installer uses
        old = os.path.join(d, "CoDMP_old.exe")
        if not os.path.isfile(old):
            os.replace(_child(d, "codmp.exe"), old)
        # The key is already in main/codkey, where CoD1x reads it
        _fetch_client(d, lambda p, m: prog(10 + int(p * 0.85), m))
        # A copy from an earlier install is not used any more
        if os.path.isdir(os.path.join(d, COPY)):
            shutil.rmtree(os.path.join(d, COPY))
        prog(100, "CoD1x installed.")
        return
    prog(0, "Building the CoD1x copy...")
    c = build_copy(d)
    _fetch_client(c, lambda p, m: prog(10 + int(p * 0.85), m))
    if source == "own":
        own_codkey(c, d)
    else:
        steam_codkey(c, steam_root)
    prog(100, "CoD1x installed.")


def update_cod1x(copy_dir: str, log=_log.info):
    """Pre-launch: download CoD1x again only when the newest release differs from the saved one."""
    url, dg = github_asset(REPO, ASSET, timeout=5)
    tag = url.split("/")[-2]
    if not dg:
        log(f"CoD1x: {tag} has no digest, update skipped")
        return
    from cod3recomp import _saved
    saved = _saved(copy_dir, META)
    if saved == {"tag": tag, "digest": dg}:
        log(f"CoD1x: {tag} is current")
        return
    log(f"CoD1x: {saved.get('tag', 'unknown')} -> {tag}")
    _fetch_client(copy_dir, lambda p, m: None, release=(url, dg))
